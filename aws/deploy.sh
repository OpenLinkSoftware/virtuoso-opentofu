configure_sql_exposure() {
    print_section "SQL Endpoint Exposure"

    read -r -p "Expose public secure SQL/ODBC/JDBC endpoint on port 1112? [y/N]: " EXPOSE_SQL
    EXPOSE_SQL=${EXPOSE_SQL:-N}
    if [[ "$EXPOSE_SQL" =~ ^[Yy]$ ]]; then
        cat <<'EOF'
Enter one or more CIDR blocks allowed to reach secure SQL on port 1112.
Examples:
  203.0.113.45/32
  203.0.113.45/32,198.51.100.27/32
  203.0.113.0/24

Use your current public IP with /32 for single-user access.
WARNING: 0.0.0.0/0 exposes secure SQL to the entire public internet.
EOF
        read -r -p "Allowed SQL CIDRs (comma-separated, required): " SQL_ALLOWED_CIDRS
        [ -n "$SQL_ALLOWED_CIDRS" ] || fail "Allowed SQL CIDRs are required when SQL exposure is enabled"
        validate_cidr_list "$SQL_ALLOWED_CIDRS" "Allowed SQL CIDRs"
        SQL_ALLOWED_CIDRS="$(printf '%s' "$SQL_ALLOWED_CIDRS" | sed 's/[[:space:]]//g')"
        set_tfvar "expose_sql_endpoint" true false
        set_tfvar "sql_allowed_cidrs" "[\"${SQL_ALLOWED_CIDRS//,/\",\"}\"]" false
    else
        set_tfvar "expose_sql_endpoint" false false
        set_tfvar "sql_allowed_cidrs" "[]" false
    fi
}

# Custom size selection
select_custom_size() {
    echo ""
    echo "Valid CPU values: 256, 512, 1024, 2048, 4096, 8192, 16384"
    echo ""
    echo "Valid CPU/Memory combinations:"
    echo "  CPU=256:   Memory=512, 1024, 2048"
