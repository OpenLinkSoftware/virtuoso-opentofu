                echo -e "${GREEN}Selected: Small Production (1 vCPU, 2 GB)${NC}"
                break
                ;;
            3)
                ECS_CPU="2048"
                ECS_MEMORY="4096"
                echo -e "${GREEN}Selected: Medium Production (2 vCPU, 4 GB)${NC}"
                break
                ;;
            4)
