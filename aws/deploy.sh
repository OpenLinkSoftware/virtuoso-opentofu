# Prompt for provider-native scheduled backup sync
configure_backup_schedule() {
    print_section "Backup Scheduling"

    echo "Virtuoso online backup has two parts:"
    echo "  1. A Virtuoso internal scheduled event creates consistent .bp backup files."
    echo "  2. AWS EventBridge runs an ECS backup-sync task to copy those files to S3."
    echo ""
    echo -e "${YELLOW}Recommended for production deployments.${NC}"
    echo ""

    local current_enabled=$(get_current_value "enable_backup_sync_schedule" "false")
    local default_answer="N"
    if [ "$current_enabled" = "true" ]; then
        default_answer="Y"
    fi

    if [ "$default_answer" = "Y" ]; then
        read -p "Enable provider-native scheduled backup sync? [Y/n]: " ENABLE_BACKUP_SCHEDULE
    else
        read -p "Enable provider-native scheduled backup sync? [y/N]: " ENABLE_BACKUP_SCHEDULE
    fi
    ENABLE_BACKUP_SCHEDULE="${ENABLE_BACKUP_SCHEDULE:-$default_answer}"

    if [[ "$ENABLE_BACKUP_SCHEDULE" =~ ^[Yy]$ ]]; then
        BACKUP_SYNC_SCHEDULE_ENABLED=true
        local current_expr=$(get_current_value "backup_sync_schedule_expression" "rate(1 day)")
        read -p "EventBridge schedule expression [${current_expr}]: " BACKUP_SYNC_SCHEDULE_EXPRESSION
        BACKUP_SYNC_SCHEDULE_EXPRESSION="${BACKUP_SYNC_SCHEDULE_EXPRESSION:-$current_expr}"
    else
        BACKUP_SYNC_SCHEDULE_ENABLED=false
        BACKUP_SYNC_SCHEDULE_EXPRESSION=$(get_current_value "backup_sync_schedule_expression" "rate(1 day)")
    fi

    set_tfvar "enable_backup_sync_schedule" "$BACKUP_SYNC_SCHEDULE_ENABLED" false
    set_tfvar "backup_sync_schedule_expression" "$BACKUP_SYNC_SCHEDULE_EXPRESSION"
}

# Install the Virtuoso internal scheduled backup event after deployment.
setup_internal_backup_schedule() {
    if [ "$(get_current_value "enable_backup_sync_schedule" "false")" = "true" ]; then
        print_section "Configuring Virtuoso Scheduled Backup"
        echo "Installing Virtuoso daily online backup event. This creates .bp files for the AWS sync schedule."
        if [ -x "${SCRIPT_DIR}/scripts/setup-scheduled-backup.sh" ]; then
            local cluster_name
            local service_name
            local region_name
            cluster_name="$($TF_CMD output -raw ecs_cluster_name)"
            service_name="$($TF_CMD output -raw ecs_service_name)"
            region_name="$($TF_CMD output -raw region 2>/dev/null || true)"
            if [ -z "$region_name" ]; then
                region_name="${AWS_REGION:-${AWS_DEFAULT_REGION:-us-east-1}}"
            fi
            echo "Waiting for ECS service to become stable before installing the Virtuoso backup schedule..."
            aws ecs wait services-stable                 --region "$region_name"                 --cluster "$cluster_name"                 --services "$service_name"
            "${SCRIPT_DIR}/scripts/setup-scheduled-backup.sh" 1440
        else
            echo -e "${YELLOW}Backup scheduler script not found or not executable.${NC}"
            echo "Run this after deployment: ./scripts/setup-scheduled-backup.sh 1440"
        fi
    fi
}

