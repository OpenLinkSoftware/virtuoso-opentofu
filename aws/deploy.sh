#!/bin/bash
# -------------------------------------------------------
# Virtuoso on AWS - Interactive Deployment Script
# -------------------------------------------------------
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TFVARS_FILE="${SCRIPT_DIR}/terraform.tfvars"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

fail() {
    echo -e "${RED}Error: $1${NC}" >&2
    exit 1
}

require_single_line() {
    local value="$1"
    local label="$2"
    case "$value" in
        *$'\n'*|*$'\r'*) fail "$label must be a single-line value" ;;
    esac
}

escape_tf_string() {
    local value="$1"
    local label="${2:-value}"
    require_single_line "$value" "$label"
    value="${value//\\/\\\\}"
    value="${value//\"/\\\"}"
    printf '%s' "$value"
}


validate_cidr_list() {
    local list_value="$1"
    local label="$2"
    local IFS=','
    local item
    local -a parts
    read -r -a parts <<< "$list_value"
    [ ${#parts[@]} -gt 0 ] || fail "$label must contain at least one CIDR"
    for item in "${parts[@]}"; do
        item="${item//[[:space:]]/}"
        [[ -n "$item" ]] || fail "$label contains an empty CIDR entry"
        [[ "$item" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$ ]] || fail "$label contains an invalid CIDR: $item"
    done
}

print_header() {
    echo ""
    echo -e "${BLUE}═══════════════════════════════════════════════════════════${NC}"
    echo -e "${BLUE}  Virtuoso on AWS – Interactive Deployment${NC}"
    echo -e "${BLUE}═══════════════════════════════════════════════════════════${NC}"
    echo ""
}

print_section() {
    echo ""
    echo -e "${GREEN}─── $1 ───${NC}"
    echo ""
}

# Check for required tools
check_prerequisites() {
    local missing=()

    if ! command -v tofu &> /dev/null && ! command -v terraform &> /dev/null; then
        missing+=("tofu or terraform")
    fi

    if ! command -v aws &> /dev/null; then
        missing+=("aws-cli")
    fi

    if [ ${#missing[@]} -ne 0 ]; then
        echo -e "${RED}Error: Missing required tools: ${missing[*]}${NC}"
        exit 1
    fi

    # Prefer tofu over terraform
    if command -v tofu &> /dev/null; then
        TF_CMD="tofu"
    else
        TF_CMD="terraform"
    fi
}

# Read current value from terraform.tfvars if it exists
get_current_value() {
    local var_name="$1"
    local default="$2"

    if [ -f "$TFVARS_FILE" ]; then
        # Use awk for more reliable parsing
        local value=$(awk -F'=' -v var="$var_name" '
            $0 ~ "^"var"[[:space:]]*=" {
                # Get everything after the =
                sub(/^[^=]*=[[:space:]]*/, "")
                # Remove surrounding quotes if present
                gsub(/^[[:space:]]*"?|"?[[:space:]]*$/, "")
                print
                exit
            }
        ' "$TFVARS_FILE" 2>/dev/null)
        if [ -n "$value" ]; then
            echo "$value"
            return
        fi
    fi
    echo "$default"
}

# Update or add a variable in terraform.tfvars
set_tfvar() {
    local var_name="$1"
    local var_value="$2"
    local is_string="${3:-true}"

    # Create file if it doesn't exist
    if [ ! -f "$TFVARS_FILE" ]; then
        cat > "$TFVARS_FILE" << 'EOF'
# -------------------------------------------------------
# Virtuoso on AWS – Configuration
# Generated by deploy.sh
# -------------------------------------------------------

EOF
    fi

    # Format the value
    if [ "$is_string" = "true" ]; then
        local formatted_value="\"$(escape_tf_string "$var_value" "$var_name")\""
    else
        local formatted_value="${var_value}"
    fi

    # Check if variable exists in file
    if grep -q "^${var_name}[[:space:]]*=" "$TFVARS_FILE" 2>/dev/null; then
        # Update existing variable (macOS compatible sed)
        if [[ "$OSTYPE" == "darwin"* ]]; then
            sed -i '' "s|^${var_name}[[:space:]]*=.*|${var_name} = ${formatted_value}|" "$TFVARS_FILE"
        else
            sed -i "s|^${var_name}[[:space:]]*=.*|${var_name} = ${formatted_value}|" "$TFVARS_FILE"
        fi
    else
        # Add new variable
        echo "${var_name} = ${formatted_value}" >> "$TFVARS_FILE"
    fi
}

# Prompt for Virtuoso image selection
select_virtuoso_image() {
    print_section "Virtuoso Image Selection"

    echo "Select the Virtuoso image to deploy:"
    echo ""

    local options=(
        "Virtuoso Open Source 7 (Free, community edition)"
        "Virtuoso Commercial 8 (Requires license file)"
    )

    PS3=$'\nEnter selection [1-2]: '
    select opt in "${options[@]}"; do
        case $REPLY in
            1)
                VIRTUOSO_IMAGE="openlink/virtuoso-opensource-7"
                VIRTUOSO_LICENSE_REQUIRED=false
                echo -e "${GREEN}Selected: Virtuoso Open Source 7${NC}"
                break
                ;;
            2)
                VIRTUOSO_IMAGE="openlink/virtuoso-closedsource-8"
                VIRTUOSO_LICENSE_REQUIRED=true
                echo -e "${GREEN}Selected: Virtuoso Commercial 8${NC}"
                break
                ;;
            *)
                echo -e "${RED}Invalid selection. Please enter 1 or 2.${NC}"
                ;;
        esac
    done

    # Prompt for image tag
    local current_tag=$(get_current_value "virtuoso_image_tag" "latest")
    echo ""
    read -p "Enter image tag [${current_tag}]: " IMAGE_TAG
    IMAGE_TAG="${IMAGE_TAG:-$current_tag}"

    set_tfvar "virtuoso_image" "$VIRTUOSO_IMAGE"
    set_tfvar "virtuoso_image_tag" "$IMAGE_TAG"
    set_tfvar "web_allowed_cidrs" '["0.0.0.0/0"]' false
    set_tfvar "virtuoso_number_of_buffers" "60%"
    set_tfvar "virtuoso_max_dirty_buffers" "45%"
}

# Prompt for license file if using commercial image
select_license_file() {
    if [ "$VIRTUOSO_LICENSE_REQUIRED" = true ]; then
        print_section "License File"

        echo -e "${YELLOW}Virtuoso Commercial 8 requires a license file.${NC}"
        echo "The license file will be copied to the EFS storage after deployment."
        echo ""

        while true; do
            read -p "Enter path to license file (virtuoso.lic): " LICENSE_PATH

            if [ -z "$LICENSE_PATH" ]; then
                echo -e "${RED}License file is required for Commercial edition.${NC}"
                continue
            fi

            # Expand ~ to home directory
            LICENSE_PATH="${LICENSE_PATH/#\~/$HOME}"

            if [ ! -f "$LICENSE_PATH" ]; then
                echo -e "${RED}File not found: ${LICENSE_PATH}${NC}"
                continue
            fi

            VIRTUOSO_LICENSE_FILE="$LICENSE_PATH"
            echo -e "${GREEN}License file: ${LICENSE_PATH}${NC}"
            set_tfvar "virtuoso_license_file" "$LICENSE_PATH"
            break
        done
    else
        set_tfvar "virtuoso_license_file" ""
    fi
}

