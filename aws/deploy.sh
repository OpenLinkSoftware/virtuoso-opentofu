# Determine the database path based on image type
get_database_path() {
    local image="${1:-$VIRTUOSO_IMAGE}"
    if [[ "$image" == *"closedsource"* ]]; then
        echo "/opt/virtuoso/database"
    else
        echo "/opt/virtuoso-opensource/database"
    fi
}

# Copy license file to EFS after deployment
copy_license_to_efs() {
    if [ "$VIRTUOSO_LICENSE_REQUIRED" = true ] && [ -n "$VIRTUOSO_LICENSE_FILE" ]; then
        print_section "Copying License File to EFS"

        local cluster_name="${PROJECT_NAME:-virtuoso}-cluster"
        local service_name="${PROJECT_NAME:-virtuoso}"
        local db_path=$(get_database_path)

        echo "Database path: ${db_path}"
        echo "Waiting for ECS task to be running..."

        # Wait for task to be running
        local max_attempts=30
        local attempt=0
        local task_arn=""

        while [ $attempt -lt $max_attempts ]; do
            task_arn=$(aws ecs list-tasks \
                --cluster "$cluster_name" \
                --service-name "$service_name" \
                --query 'taskArns[0]' \
                --output text 2>/dev/null)

            if [ -n "$task_arn" ] && [ "$task_arn" != "None" ]; then
                local status=$(aws ecs describe-tasks \
                    --cluster "$cluster_name" \
                    --tasks "$task_arn" \
                    --query 'tasks[0].lastStatus' \
                    --output text 2>/dev/null)

                if [ "$status" = "RUNNING" ]; then
                    echo -e "${GREEN}Task is running.${NC}"
                    break
                fi
            fi

            attempt=$((attempt + 1))
            echo "  Waiting... (attempt $attempt/$max_attempts)"
            sleep 10
        done

        if [ $attempt -eq $max_attempts ]; then
            echo -e "${RED}Timeout waiting for task to start.${NC}"
            echo "You can manually copy the license file later using:"
            echo "  ./deploy.sh --copy-license"
            return 1
        fi

        # Get task ID from ARN
        local task_id=$(echo "$task_arn" | awk -F/ '{print $NF}')

        echo "Copying license file to ${db_path}/virtuoso.lic ..."

        # Read license file content
        local license_content=$(base64 < "$VIRTUOSO_LICENSE_FILE")

        # Copy via ECS Exec using a here-document approach for reliability
        # First, write to a temp file, then move it
        aws ecs execute-command \
            --cluster "$cluster_name" \
            --task "$task_id" \
            --container virtuoso \
            --command "sh -c 'echo \"$license_content\" | base64 -d > ${db_path}/virtuoso.lic && chmod 644 ${db_path}/virtuoso.lic && ls -la ${db_path}/virtuoso.lic'" \
            --interactive

        if [ $? -eq 0 ]; then
            echo -e "${GREEN}License file copied successfully.${NC}"
            echo ""
            echo -e "${YELLOW}Restarting Virtuoso to apply the license...${NC}"
            echo "This requires a clean stop/start cycle (rolling updates won't work due to lock file)."
            echo ""

            # Stop the service (scale to 0)
            echo "Stopping service..."
            aws ecs update-service \
                --cluster "$cluster_name" \
                --service "$service_name" \
                --desired-count 0 \
                --query 'service.serviceName' \
                --output text > /dev/null

            # Wait for tasks to drain
            echo "Waiting for tasks to stop..."
            local drain_attempts=0
            local max_drain_attempts=30
            while [ $drain_attempts -lt $max_drain_attempts ]; do
                local running_count=$(aws ecs describe-services \
                    --cluster "$cluster_name" \
                    --services "$service_name" \
                    --query 'services[0].runningCount' \
                    --output text 2>/dev/null)

                if [ "$running_count" = "0" ]; then
                    echo -e "${GREEN}Service stopped.${NC}"
                    break
                fi

                drain_attempts=$((drain_attempts + 1))
                echo "  Still running: $running_count tasks (attempt $drain_attempts/$max_drain_attempts)"
                sleep 10
            done

            # Start the service (single instance)
            echo "Starting service..."
            aws ecs update-service \
                --cluster "$cluster_name" \
                --service "$service_name" \
                --desired-count 1 \
                --query 'service.serviceName' \
                --output text > /dev/null

            echo -e "${GREEN}Service restart initiated. Virtuoso will now start with the license.${NC}"
        else
            echo -e "${RED}Failed to copy license file.${NC}"
            echo ""
            echo "You can manually copy the license file by running:"
            echo "  TASK_ID=\$(aws ecs list-tasks --cluster $cluster_name --service-name $service_name --query 'taskArns[0]' --output text | awk -F/ '{print \$NF}')"
            echo "  aws ecs execute-command --cluster $cluster_name --task \$TASK_ID --container virtuoso --interactive --command '/bin/bash'"
            echo "  # Then inside the container:"
            echo "  # Copy your license content to ${db_path}/virtuoso.lic"
            return 1
        fi
    fi
}

# Run deployment
run_deployment() {
    print_section "Deployment"

    echo "Initializing ${TF_CMD}..."
    $TF_CMD init

    echo ""
    echo "Planning deployment..."
    $TF_CMD plan -out=tfplan

    echo ""
    read -p "Apply this plan? (yes/no): " CONFIRM

    if [ "$CONFIRM" = "yes" ]; then
        echo ""
        echo "Applying..."
        $TF_CMD apply tfplan
        rm -f tfplan

        # Copy license if needed
        if [ "$VIRTUOSO_LICENSE_REQUIRED" = true ]; then
            copy_license_to_efs
        fi

        setup_internal_backup_schedule

        print_section "Deployment Complete"

        echo "Outputs:"
        $TF_CMD output

        echo ""
        echo -e "${GREEN}Virtuoso has been deployed successfully!${NC}"
        echo ""
        echo "To retrieve the DBA password:"
        echo "  aws secretsmanager get-secret-value \\"
        echo "    --secret-id ${PROJECT_NAME:-virtuoso}-dba-password \\"
        echo "    --query SecretString --output text"

        if [ "$VIRTUOSO_LICENSE_REQUIRED" = true ]; then
            echo ""
            echo -e "${YELLOW}Note: Commercial license was copied and service restarted.${NC}"
            echo "Check the Virtuoso log to confirm the license was applied:"
            echo "  aws logs tail /ecs/${PROJECT_NAME:-virtuoso} --follow"
        fi
    else
        echo "Deployment cancelled."
        rm -f tfplan
    fi
}

# Main menu
main_menu() {
    print_header
    check_prerequisites

    echo "This script will guide you through configuring and deploying"
    echo "Virtuoso on AWS ECS Fargate."
    echo ""

    local options=(
        "Interactive Setup (configure and deploy)"
        "Deploy with current settings"
        "Copy license file to running deployment"
        "Destroy deployment"
        "Exit"
    )

    PS3=$'\nSelect an option: '
    select opt in "${options[@]}"; do
        case $REPLY in
            1)
                select_region
                select_project_name
                select_virtuoso_image
                select_license_file
                select_container_size
                configure_sql_exposure
                configure_backup_schedule
                show_summary

                read -p "Proceed with deployment? (yes/no): " CONFIRM
                if [ "$CONFIRM" = "yes" ]; then
                    run_deployment
                fi
                break
                ;;
            2)
                # Load current values
                VIRTUOSO_IMAGE=$(get_current_value "virtuoso_image" "openlink/virtuoso-opensource-7")
                IMAGE_TAG=$(get_current_value "virtuoso_image_tag" "latest")
                ECS_CPU=$(get_current_value "ecs_cpu" "512")
                ECS_MEMORY=$(get_current_value "ecs_memory" "1024")
                VIRTUOSO_LICENSE_FILE=$(get_current_value "virtuoso_license_file" "")
                BACKUP_SYNC_SCHEDULE_ENABLED=$(get_current_value "enable_backup_sync_schedule" "false")
                BACKUP_SYNC_SCHEDULE_EXPRESSION=$(get_current_value "backup_sync_schedule_expression" "rate(1 day)")

                if [[ "$VIRTUOSO_IMAGE" == *"closedsource"* ]]; then
                    VIRTUOSO_LICENSE_REQUIRED=true
                else
                    VIRTUOSO_LICENSE_REQUIRED=false
                fi

                show_summary
                run_deployment
                break
                ;;
            3)
                VIRTUOSO_LICENSE_REQUIRED=true
                PROJECT_NAME=$(get_current_value "project_name" "virtuoso")
                VIRTUOSO_IMAGE=$(get_current_value "virtuoso_image" "openlink/virtuoso-opensource-7")

                read -p "Enter path to license file: " VIRTUOSO_LICENSE_FILE
                VIRTUOSO_LICENSE_FILE="${VIRTUOSO_LICENSE_FILE/#\~/$HOME}"

                if [ -f "$VIRTUOSO_LICENSE_FILE" ]; then
                    copy_license_to_efs
                else
                    echo -e "${RED}File not found: ${VIRTUOSO_LICENSE_FILE}${NC}"
                fi
                break
                ;;
            4)
                print_section "Destroy Deployment"
                echo -e "${RED}WARNING: This will destroy all Virtuoso infrastructure!${NC}"
                read -p "Are you sure? (yes/no): " CONFIRM
                if [ "$CONFIRM" = "yes" ]; then
                    $TF_CMD destroy
                fi
                break
                ;;
            5)
                echo "Exiting."
                exit 0
                ;;
            *)
                echo -e "${RED}Invalid selection.${NC}"
                ;;
        esac
    done
}

